import path from 'node:path';
import os from 'node:os';
import {dataDirectory} from '../src/paths.js';
import {syncCursorPlugin} from '../src/cursor-install.js';
import {installCursorUserHooks} from '../src/cursor-hook-config.js';
if(!process.argv[2])throw Error('Usage: node scripts/install-cursor-plugin.mjs <built-plugin-directory>');
const target=path.resolve(os.homedir(),'.cursor/plugins/local/board-pet');
const result=await syncCursorPlugin(path.resolve(process.argv[2]),target,{dir:dataDirectory()});
await installCursorUserHooks(path.join(os.homedir(),'.cursor/hooks.json'),target);
console.log(JSON.stringify(result));console.log('Restart Cursor, then start a new Agent conversation.');
